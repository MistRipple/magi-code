import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const output = new URL('./include-journal.generated.mjs', import.meta.url);
const metadata = JSON.parse(await readFile(new URL('./node_modules/@deepseek-ai/cordis-plugin-include/package.json', import.meta.url), 'utf8'));
const license = await readFile(new URL('./node_modules/@deepseek-ai/cordis-plugin-include/LICENSE', import.meta.url), 'utf8');
const result = await build({
  absWorkingDir: root, entryPoints: ['include-journal.entry.mjs'], bundle: true,
  platform: 'node', target: 'node26', format: 'esm', write: false,
  external: ['@deepseek-ai/cosmokit'],
  banner: { js: `// Generated by build-include-journal.mjs from @deepseek-ai/cordis-plugin-include@${metadata.version}. Do not edit.\n/*\n${license.trim()}\n*/` },
});
const content = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Upstream Include helpers changed; run npm run include:generate');
} else await writeFile(output, content);
