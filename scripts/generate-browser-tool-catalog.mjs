#!/usr/bin/env node

/* 从 browser-tool.schema.json 的唯一目录生成 Rust 与 TypeScript 浏览器工具目录。 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'contracts/desktop-browser/browser-tool.schema.json');
const rustPath = resolve(root, 'crates/magi-browser-authority/src/browser_tool_catalog.generated.rs');
const tsPath = resolve(root, 'contracts/desktop-browser/src/browser-tool-catalog.generated.ts');
const checkOnly = process.argv.includes('--check');

function fail(message) {
  throw new Error(`Browser tool catalog generation failed: ${message}`);
}

function rustString(value) {
  return JSON.stringify(value);
}

function tsString(value) {
  return JSON.stringify(value);
}

function loadCatalog(schema) {
  const catalog = schema['x-magi-browser-tool-catalog'];
  if (!Array.isArray(catalog) || catalog.length === 0) {
    fail('x-magi-browser-tool-catalog 必须是非空数组');
  }
  const names = new Set();
  const variants = new Set();
  for (const entry of catalog) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) fail('工具目录条目必须是对象');
    if (typeof entry.name !== 'string' || !/^browser_[a-z0-9_]+$/u.test(entry.name)) {
      fail(`工具名称无效: ${String(entry.name)}`);
    }
    if (typeof entry.rustVariant !== 'string' || !/^[A-Z][A-Za-z0-9]*$/u.test(entry.rustVariant)) {
      fail(`工具 ${entry.name} 的 rustVariant 无效`);
    }
    if (!['read', 'write', 'mixed'].includes(entry.access)) {
      fail(`工具 ${entry.name} 的 access 必须是 read、write 或 mixed`);
    }
    if (typeof entry.description !== 'string' || !entry.description.trim()) {
      fail(`工具 ${entry.name} 缺少 description`);
    }
    if (!entry.inputSchema || typeof entry.inputSchema !== 'object' || Array.isArray(entry.inputSchema)
      || entry.inputSchema.type !== 'object') {
      fail(`工具 ${entry.name} 的 inputSchema 必须是 object schema`);
    }
    if (names.has(entry.name) || variants.has(entry.rustVariant)) {
      fail(`工具目录名称或 Rust 变体重复: ${entry.name}/${entry.rustVariant}`);
    }
    names.add(entry.name);
    variants.add(entry.rustVariant);
  }
  const schemaNames = schema.$defs?.browserToolName?.enum;
  if (!Array.isArray(schemaNames) || schemaNames.length !== catalog.length
    || schemaNames.some((name, index) => name !== catalog[index]?.name)) {
    fail('$defs.browserToolName.enum 必须与唯一工具目录按顺序完全一致');
  }
  return catalog;
}

function renderRust(schema, catalog) {
  const variants = catalog.map((entry) => `    ${entry.rustVariant},`);
  const all = catalog.map((entry) => `        Self::${entry.rustVariant},`);
  const names = catalog.map((entry) => `            Self::${entry.rustVariant} => ${rustString(entry.name)},`);
  const fromName = catalog.map((entry) => `            ${rustString(entry.name)} => Some(Self::${entry.rustVariant}),`);
  const access = catalog.map((entry) => `            Self::${entry.rustVariant} => BrowserToolAccess::${entry.access[0].toUpperCase()}${entry.access.slice(1)},`);
  const descriptions = catalog.map((entry) => {
    const value = rustString(entry.description);
    return entry.description.length > 100
      ? [
        `            Self::${entry.rustVariant} => {`,
        `                ${value}`,
        '            }',
      ].join('\n')
      : `            Self::${entry.rustVariant} => ${value},`;
  });
  const schemas = catalog.map((entry) => [
    `            Self::${entry.rustVariant} => {`,
    `                r#"${JSON.stringify(entry.inputSchema)}"#`,
    '            }',
  ].join('\n'));
  return [
    '// @generated by scripts/generate-browser-tool-catalog.mjs from contracts/desktop-browser/browser-tool.schema.json.',
    '// DO NOT EDIT. Change the schema and rerun: npm run browser-tool-catalog:generate',
    '',
    'use serde::{Deserialize, Serialize};',
    '',
    'pub const BROWSER_TOOL_CATALOG_SCHEMA_ID: &str =',
    `    ${rustString(schema.$id)};`,
    `pub const BROWSER_TOOL_CATALOG_SIZE: usize = ${catalog.length};`,
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]',
    '#[serde(rename_all = "snake_case")]',
    'pub enum BrowserToolKind {',
    ...variants,
    '}',
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]',
    '#[serde(rename_all = "snake_case")]',
    'pub enum BrowserToolAccess {',
    '    Read,',
    '    Write,',
    '    Mixed,',
    '}',
    '',
    'impl BrowserToolKind {',
    `    pub const ALL: [Self; ${catalog.length}] = [`,
    ...all,
    '    ];',
    '',
    "    pub fn name(self) -> &'static str {",
    '        match self {',
    ...names,
    '        }',
    '    }',
    '',
    '    pub fn from_name(name: &str) -> Option<Self> {',
    '        match name {',
    ...fromName,
    '            _ => None,',
    '        }',
    '    }',
    '',
    '    pub fn catalog_access(self) -> BrowserToolAccess {',
    '        match self {',
    ...access,
    '        }',
    '    }',
    '',
    "    pub fn description(self) -> &'static str {",
    '        match self {',
    ...descriptions,
    '        }',
    '    }',
    '',
    "    pub fn input_schema_json(self) -> &'static str {",
    '        match self {',
    ...schemas,
    '        }',
    '    }',
    '',
    '    pub fn input_schema(self) -> serde_json::Value {',
    '        serde_json::from_str(self.input_schema_json())',
    '            .expect("generated browser tool input schema must be valid JSON")',
    '    }',
    '',
    '    pub fn is_supported(self) -> bool {',
    '        Self::ALL.contains(&self)',
    '    }',
    '}',
    '',
  ].join('\n');
}

function renderTypeScript(schema, catalog) {
  const names = catalog.map((entry) => tsString(entry.name)).join(' | ');
  const entries = catalog.map((entry) => `  { name: ${tsString(entry.name)}, rustVariant: ${tsString(entry.rustVariant)}, access: ${tsString(entry.access)}, description: ${tsString(entry.description)}, inputSchema: ${JSON.stringify(entry.inputSchema)} },`);
  return [
    '// @generated by scripts/generate-browser-tool-catalog.mjs from contracts/desktop-browser/browser-tool.schema.json.',
    '// DO NOT EDIT. Change the schema and rerun: npm run browser-tool-catalog:generate',
    '',
    `export const BROWSER_TOOL_CATALOG_SCHEMA_ID = ${tsString(schema.$id)} as const;`,
    `export type BrowserToolName = ${names};`,
    'export type BrowserToolAccess = "read" | "write" | "mixed";',
    '',
    'export interface BrowserToolCatalogEntry {',
    '  name: BrowserToolName;',
    '  rustVariant: string;',
    '  access: BrowserToolAccess;',
    '  description: string;',
    '  inputSchema: Record<string, unknown>;',
    '}',
    '',
    'export const BROWSER_TOOL_CATALOG: readonly BrowserToolCatalogEntry[] = [',
    ...entries,
    '] as const;',
    '',
    'export function browserToolCatalogEntry(name: string): BrowserToolCatalogEntry | undefined {',
    '  return BROWSER_TOOL_CATALOG.find((entry) => entry.name === name);',
    '}',
    '',
  ].join('\n');
}

async function writeOrCheck(path, content) {
  if (checkOnly) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== content) fail(`${path.replace(`${root}/`, '')} 已过期，请执行 npm run browser-tool-catalog:generate`);
    return;
  }
  await writeFile(path, content, 'utf8');
}

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const catalog = loadCatalog(schema);
await Promise.all([
  writeOrCheck(rustPath, renderRust(schema, catalog)),
  writeOrCheck(tsPath, renderTypeScript(schema, catalog)),
]);
process.stdout.write(`Browser 工具目录 ${checkOnly ? '校验' : '生成'}通过，共 ${catalog.length} 项。\n`);
