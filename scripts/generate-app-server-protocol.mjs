#!/usr/bin/env node

/* 从唯一 JSON Schema 生成 App Server 的 Rust/TypeScript wire 类型。 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'contracts/app-server/app-server.schema.json');
const rustPath = resolve(root, 'crates/magi-app-server-protocol/src/generated.rs');
const tsPath = resolve(root, 'web/src/shared/app-server-protocol.generated.ts');
const requiredDefinitions = [
  'ProtocolVersion', 'ClientInfo', 'ClientCapabilities', 'EmptyParams', 'PingResult',
  'ServerCapabilities',
  'InitializeParams', 'InitializeResult', 'JsonRpcRequest', 'JsonRpcNotification',
  'JsonRpcResponse', 'JsonRpcServerRequest', 'JsonRpcServerNotification',
  'JsonRpcServerResponse', 'JsonRpcError', 'CancelNotification',
  'BrowserToolsListParams', 'BrowserToolParams', 'ApprovalRequestParams',
  'EventSubscribeParams', 'SessionListParams', 'SessionReadParams',
  'TurnStartParams', 'SessionSummary', 'SessionListResult', 'SessionReadResult',
  'TurnStartResult', 'EventSubscribeResult', 'BrowserToolsListResult',
  'BrowserToolResult', 'ApprovalDecision',
  'EventCategory', 'CanonicalTurnStatus', 'CanonicalTurnItemKind',
  'CanonicalTurnItemStatus', 'CanonicalTurnEventKind', 'CanonicalTurnVisibility',
  'CanonicalToolCall', 'CanonicalWorkerRef', 'CanonicalTurnItem', 'CanonicalTurn',
  'CanonicalTurnEvent', 'EventEnvelope', 'EventStreamSnapshot', 'EventNotificationParams',
];
const rustHeader = [
  '// @generated by scripts/generate-app-server-protocol.mjs from contracts/app-server/app-server.schema.json.',
  '// DO NOT EDIT. Change the schema and rerun: npm run protocol:generate', '',
].join('\n');
const tsHeader = [
  '// @generated by scripts/generate-app-server-protocol.mjs from contracts/app-server/app-server.schema.json.',
  '// DO NOT EDIT. Change the schema and rerun: npm run protocol:generate', '',
].join('\n');

function fail(message) {
  throw new Error(`App Server protocol generation failed: ${message}`);
}

function refName(ref) {
  const prefix = '#/$defs/';
  if (typeof ref !== 'string' || !ref.startsWith(prefix)) fail(`unsupported reference: ${String(ref)}`);
  return ref.slice(prefix.length);
}

function methodVariant(method) {
  const words = method
    .replace(/^\$\//, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  const value = words.map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`).join('');
  return value || 'Method';
}

function validateMethodSignatures(schema) {
  const methods = schema['x-methods'];
  const signatures = schema['x-method-signatures'];
  if (!Array.isArray(methods) || new Set(methods).size !== methods.length) {
    fail('x-methods must not contain duplicate method names');
  }
  if (!signatures || typeof signatures !== 'object' || Array.isArray(signatures)) {
    fail('schema must declare an object-valued x-method-signatures');
  }
  const methodSet = new Set(methods);
  const signatureNames = Object.keys(signatures);
  const signatureSet = new Set(signatureNames);
  const missing = methods.filter((method) => !signatureSet.has(method));
  const extra = signatureNames.filter((method) => !methodSet.has(method));
  if (missing.length || extra.length) {
    const details = [];
    if (missing.length) details.push(`missing: ${missing.join(', ')}`);
    if (extra.length) details.push(`extra: ${extra.join(', ')}`);
    fail(`x-method-signatures must exactly match x-methods (${details.join('; ')})`);
  }
  for (const method of methods) {
    const signature = signatures[method];
    if (!signature || typeof signature !== 'object' || Array.isArray(signature)) {
      fail(`x-method-signatures[${method}] must be an object`);
    }
    if (!['request', 'notification'].includes(signature.kind)) {
      fail(`x-method-signatures[${method}].kind must be request or notification`);
    }
    if (typeof signature.params !== 'string' || !schema.$defs[signature.params]) {
      fail(`x-method-signatures[${method}].params must reference an existing $defs entry`);
    }
    if (signature.kind === 'request') {
      if (typeof signature.result !== 'string' || !schema.$defs[signature.result]) {
        fail(`x-method-signatures[${method}].result must reference an existing $defs entry`);
      }
    } else if (Object.prototype.hasOwnProperty.call(signature, 'result')) {
      fail(`notification ${method} must not declare a result type`);
    }
    if (signature.serverRequest !== undefined && typeof signature.serverRequest !== 'boolean') {
      fail(`x-method-signatures[${method}].serverRequest must be boolean`);
    }
    if (signature.serverRequest === true && signature.kind !== 'request') {
      fail(`notification ${method} cannot be a server request`);
    }
  }
}

function loadSchema(raw) {
  let schema;
  try { schema = JSON.parse(raw); } catch (error) { fail(`schema is not valid JSON: ${error.message}`); }
  if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema') fail('schema must declare JSON Schema Draft 2020-12');
  if (!schema.$defs || typeof schema.$defs !== 'object' || Array.isArray(schema.$defs)) fail('schema must contain an object-valued $defs');
  const protocol = schema['x-protocol'];
  if (!protocol || typeof protocol.name !== 'string' || !Number.isInteger(protocol.major) || !Number.isInteger(protocol.minor) || protocol.jsonrpcVersion !== '2.0') {
    fail('schema must declare x-protocol name/major/minor/jsonrpcVersion');
  }
  if (!Array.isArray(schema['x-methods']) || schema['x-methods'].some((method) => typeof method !== 'string' || !method.trim())) {
    fail('schema must declare a non-empty x-methods string list');
  }
  validateMethodSignatures(schema);
  for (const name of requiredDefinitions) if (!schema.$defs[name]) fail(`missing required definition: ${name}`);
  return schema;
}

function nullableSchema(schema) {
  if (Array.isArray(schema?.type) && schema.type.includes('null')) {
    return { nullable: true, value: { ...schema, type: schema.type.find((type) => type !== 'null') } };
  }
  if (schema?.oneOf?.length === 2) {
    const nullIndex = schema.oneOf.findIndex((item) => item?.type === 'null');
    if (nullIndex >= 0) return { nullable: true, value: schema.oneOf[1 - nullIndex] };
  }
  return { nullable: false, value: schema };
}

function rustReference(name) {
  if (name === 'JsonRpcRequestId') return 'RequestId';
  if (name === 'JsonRpcError') return 'ErrorObject';
  return name;
}

function rustType(schema, context) {
  if (schema?.['x-rust-type']) return schema['x-rust-type'];
  if (schema?.$ref) return rustReference(refName(schema.$ref));
  const nullable = nullableSchema(schema);
  if (nullable.nullable) return `Option<${rustType(nullable.value, context)}>`;
  if (!schema || Object.keys(schema).length === 0) return 'Value';
  if (schema.type === 'string') return schema.enum ? context : 'String';
  if (schema.type === 'integer') return schema.maximum !== undefined && schema.maximum <= 65535 ? 'u16' : 'i64';
  if (schema.type === 'number') return 'serde_json::Number';
  if (schema.type === 'boolean') return 'bool';
  if (schema.type === 'array') return `Vec<${rustType(schema.items ?? {}, `${context}Item`)}>`;
  if (schema.type === 'null') return 'Option<Value>';
  if (schema.oneOf) return context;
  if (schema.type === 'object') return 'Value';
  fail(`unsupported Rust schema type in ${context}`);
}

function tsType(schema, context) {
  if (schema?.['x-ts-type']) return schema['x-ts-type'];
  if (schema?.$ref) return refName(schema.$ref);
  const nullable = nullableSchema(schema);
  if (nullable.nullable) return `${tsType(nullable.value, context)} | null`;
  if (!schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.type === 'string') return schema.enum ? context : 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'array') return `Array<${tsType(schema.items ?? {}, `${context}Item`)}>`;
  if (schema.type === 'null') return 'null';
  if (schema.oneOf) return schema.oneOf.map((item) => tsType(item, context)).join(' | ');
  if (schema.type === 'object') return 'Record<string, unknown>';
  fail(`unsupported TypeScript schema type in ${context}`);
}

function rustFieldName(name) {
  return name.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function tsPropertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function rustEnum(name, definition) {
  const variants = definition.enum.map((value) => {
    const pascal = value.replace(/[^A-Za-z0-9]+(.)?/g, (_, next) => next ? next.toUpperCase() : '');
    const variant = value === '2.0'
      ? 'V2'
      : `${pascal.charAt(0).toUpperCase()}${pascal.slice(1)}`.replace(/^[0-9]/, 'Value$&') || 'Value';
    return `    #[serde(rename = ${JSON.stringify(value)})]\n    ${variant},`;
  });
  return ['#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]', '#[serde(rename_all = "camelCase")]', `pub enum ${name} {`, ...variants, '}'].join('\n');
}

function rustUnionVariantName(schema, index) {
  if (schema?.$ref) {
    const name = refName(schema.$ref).replace(/^JsonRpc/, '').replace(/Response$/, '').replace(/^Client|^Server/, '');
    return name || `Variant${index + 1}`;
  }
  if (schema?.type === 'string') return 'String';
  if (schema?.type === 'number' || schema?.type === 'integer') return 'Number';
  return `Variant${index + 1}`;
}

function rustStruct(name, definition) {
  const required = new Set(definition.required ?? []);
  const fields = Object.entries(definition.properties ?? {}).map(([jsonName, property]) => {
    const field = rustFieldName(jsonName);
    const context = `${name}${field[0].toUpperCase()}${field.slice(1)}`;
    const defaulted = property['x-rust-default'] === true;
    const nullable = nullableSchema(property);
    let type = rustType(property, context);
    const attributes = [];
    if (!required.has(jsonName) && !defaulted && !nullable.nullable) type = `Option<${type}>`;
    if (defaulted || !required.has(jsonName)) attributes.push('    #[serde(default)]');
    // Required nullable fields are part of the wire shape even when their value is null.
    // Only genuinely optional fields may be omitted during serialization.
    if (type.startsWith('Option<') && !required.has(jsonName)) {
      attributes.push('    #[serde(skip_serializing_if = "Option::is_none")]');
    }
    // Rust structs use camelCase as the default, but the existing EventEnvelope
    // wire contract intentionally remains snake_case. Preserve every explicit
    // snake_case schema property instead of letting serde rename it.
    if (jsonName !== field || jsonName.includes('_')) {
      attributes.push(`    #[serde(rename = ${JSON.stringify(jsonName)})]`);
    }
    return [...attributes, `    pub ${field}: ${type},`].join('\n');
  });
  const derives = ['Clone', 'Debug', 'PartialEq', 'Serialize', 'Deserialize'];
  if (definition['x-rust-derive-default']) derives.push('Default');
  const declaration = fields.length
    ? [`pub struct ${name} {`, ...fields, '}']
    : [`pub struct ${name} {}`];
  return [`#[derive(${derives.join(', ')})]`, '#[serde(rename_all = "camelCase", deny_unknown_fields)]', ...declaration].join('\n');
}

function requestIdRust() {
  return [
    '#[derive(Clone, Debug, PartialEq, Eq, Hash)]',
    'pub enum RequestId {',
    '    String(String),', '    Number(String),', '}', '',
    'impl RequestId {',
    '    pub fn new(value: impl Into<String>) -> Result<Self, crate::ProtocolError> {',
    '        let value = value.into();',
    '        if value.trim().is_empty() {',
    '            return Err(crate::ProtocolError::InvalidRequest(',
    '                "request id 不能为空".to_string(),',
    '            ));',
    '        }', '        Ok(Self::String(value))', '    }', '',
    '    pub fn as_str(&self) -> &str {',
    '        match self {',
    '            Self::String(value) | Self::Number(value) => value,',
    '        }',
    '    }', '}', '',
    'impl Serialize for RequestId {',
    '    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>',
    '    where',
    '        S: serde::Serializer,',
    '    {',
    '        match self {',
    '            Self::String(value) => serializer.serialize_str(value),',
    '            Self::Number(value) => value',
    '                .parse::<serde_json::Number>()',
    '                .map_err(|_| serde::ser::Error::custom("request id 数字无法序列化"))?',
    '                .serialize(serializer),',
    '        }', '    }', '}', '',
    "impl<'de> Deserialize<'de> for RequestId {",
    '    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>',
    '    where',
    '        D: serde::Deserializer<\'de>,',
    '    {',
    '        match Value::deserialize(deserializer)? {',
    '            Value::String(value) => Self::new(value).map_err(serde::de::Error::custom),',
    '            Value::Number(value) => Ok(Self::Number(value.to_string())),',
    '            _ => Err(serde::de::Error::custom("request id 必须是字符串或数字")),',
    '        }', '    }', '}', '',
    'pub type JsonRpcRequestId = RequestId;',
  ].join('\n');
}

function requestMethods(schema) {
  return schema['x-methods'].filter((method) => schema['x-method-signatures'][method].kind === 'request');
}

function notificationMethods(schema) {
  return schema['x-methods'].filter((method) => schema['x-method-signatures'][method].kind === 'notification');
}

function rustMethodMapping(schema) {
  const requests = requestMethods(schema);
  const notifications = notificationMethods(schema);
  const signatures = schema['x-methods'].map((method) => {
    const signature = schema['x-method-signatures'][method];
    return [
      '    AppServerMethodSignature {',
      `        method: ${JSON.stringify(method)},`,
      `        kind: AppServerMethodKind::${signature.kind === 'request' ? 'Request' : 'Notification'},`,
      `        params: ${JSON.stringify(signature.params)},`,
      `        result: ${signature.result ? `Some(${JSON.stringify(signature.result)})` : 'None'},`,
      `        server_request: ${signature.serverRequest === true},`,
      '    },',
    ];
  });
  const requestVariants = requests.map((method) => `    ${methodVariant(method)},`).join('\n');
  const notificationVariants = notifications.map((method) => `    ${methodVariant(method)},`).join('\n');
  const requestParams = requests.map((method) => `    ${methodVariant(method)}(${schema['x-method-signatures'][method].params}),`).join('\n');
  const notificationParams = notifications.map((method) => `    ${methodVariant(method)}(${schema['x-method-signatures'][method].params}),`).join('\n');
  const results = requests.map((method) => `    ${methodVariant(method)}(${schema['x-method-signatures'][method].result}),`).join('\n');
  const requestAsStr = requests.map((method) => `            Self::${methodVariant(method)} => ${JSON.stringify(method)},`).join('\n');
  const notificationAsStr = notifications.map((method) => `            Self::${methodVariant(method)} => ${JSON.stringify(method)},`).join('\n');
  return [
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum AppServerMethodKind {',
    '    Request,',
    '    Notification,',
    '}',
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct AppServerMethodSignature {',
    '    pub method: &\'static str,',
    '    pub kind: AppServerMethodKind,',
    '    pub params: &\'static str,',
    '    pub result: Option<&\'static str>,',
    '    pub server_request: bool,',
    '}',
    '',
    'pub const APP_SERVER_METHOD_SIGNATURES: &[AppServerMethodSignature] = &[',
    ...signatures.flat(),
    '];',
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum AppServerRequestMethod {',
    requestVariants,
    '}',
    '',
    'impl AppServerRequestMethod {',
    '    pub const ALL: &[Self] = &[',
    ...requests.map((method) => `        Self::${methodVariant(method)},`),
    '    ];',
    '',
    '    pub const fn as_str(self) -> &\'static str {',
    '        match self {',
    requestAsStr,
    '        }',
    '    }',
    '}',
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub enum AppServerNotificationMethod {',
    notificationVariants,
    '}',
    '',
    'impl AppServerNotificationMethod {',
    ...(notifications.length <= 2
      ? [`    pub const ALL: &[Self] = &[${notifications.map((method) => `Self::${methodVariant(method)}`).join(', ')}];`]
      : [
          '    pub const ALL: &[Self] = &[',
          ...notifications.map((method) => `        Self::${methodVariant(method)},`),
          '    ];',
        ]),
    '',
    '    pub const fn as_str(self) -> &\'static str {',
    '        match self {',
    notificationAsStr,
    '        }',
    '    }',
    '}',
    '',
    '#[derive(Clone, Debug, PartialEq)]',
    'pub enum AppServerRequestParams {',
    requestParams,
    '}',
    '',
    '#[derive(Clone, Debug, PartialEq)]',
    'pub enum AppServerNotificationParams {',
    notificationParams,
    '}',
    '',
    '#[derive(Clone, Debug, PartialEq)]',
    'pub enum AppServerResult {',
    results,
    '}',
  ].join('\n');
}

function typeScriptMethodMapping(schema) {
  const requests = requestMethods(schema);
  const notifications = notificationMethods(schema);
  const methodUnion = (methods) => methods.map((method) => JSON.stringify(method)).join(' | ') || 'never';
  const params = schema['x-methods'].map((method) => `  ${tsPropertyName(method)}: ${schema['x-method-signatures'][method].params};`);
  const results = requests.map((method) => `  ${tsPropertyName(method)}: ${schema['x-method-signatures'][method].result};`);
  const signatures = schema['x-methods'].map((method) => {
    const signature = schema['x-method-signatures'][method];
    const result = signature.result ? `,\n    result: ${JSON.stringify(signature.result)}` : '';
    const serverRequest = signature.serverRequest === true ? ',\n    serverRequest: true' : '';
    return `  ${JSON.stringify(method)}: {\n    kind: ${JSON.stringify(signature.kind)},\n    params: ${JSON.stringify(signature.params)}${result}${serverRequest}\n  }`;
  });
  return [
    `export type AppServerRequestMethod = ${methodUnion(requests)};`,
    `export type AppServerNotificationMethod = ${methodUnion(notifications)};`,
    'export type AppServerMethod = AppServerRequestMethod | AppServerNotificationMethod;',
    '',
    'export interface AppServerMethodParams {',
    ...params,
    '}',
    '',
    'export interface AppServerMethodResults {',
    ...results,
    '}',
    '',
    'export type AppServerRequestParams<M extends AppServerRequestMethod> = AppServerMethodParams[M];',
    'export type AppServerRequestResult<M extends AppServerRequestMethod> = AppServerMethodResults[M];',
    'export type AppServerNotificationParams<M extends AppServerNotificationMethod> = AppServerMethodParams[M];',
    '',
    'export interface AppServerMethodSignature {',
    '  kind: "request" | "notification";',
    '  params: string;',
    '  result?: string;',
    '  serverRequest?: boolean;',
    '}',
    '',
    'export const APP_SERVER_METHOD_SIGNATURES = {',
    ...signatures.map((value, index) => `${value}${index === signatures.length - 1 ? '' : ','}`),
    '} as const;',
  ].join('\n');
}

function generateRust(schema) {
  const protocol = schema['x-protocol'];
  const output = [
    rustHeader,
    'use serde::{Deserialize, Serialize};',
    'use serde_json::Value;',
    '',
    `pub const PROTOCOL_NAME: &str = ${JSON.stringify(protocol.name)};`,
    `pub const PROTOCOL_MAJOR: u16 = ${protocol.major};`,
    `pub const PROTOCOL_MINOR: u16 = ${protocol.minor};`,
    `pub const JSONRPC_VERSION: &str = ${JSON.stringify(protocol.jsonrpcVersion)};`,
    'pub const APP_SERVER_METHODS: &[&str] = &[',
    ...schema['x-methods'].map((method) => `    ${JSON.stringify(method)},`),
    '];',
    '',
    rustMethodMapping(schema),
    '',
  ];
  for (const [name, definition] of Object.entries(schema.$defs)) {
    if (name === 'JsonRpcRequestId') { output.push(requestIdRust(), ''); continue; }
    if (name === 'JsonRpcError') { output.push(rustStruct('ErrorObject', definition), 'pub type JsonRpcError = ErrorObject;', ''); continue; }
    if (definition.$ref) { output.push(`pub type ${name} = ${rustReference(refName(definition.$ref))};`, ''); continue; }
    if (definition.type === 'object') { output.push(rustStruct(name, definition), ''); continue; }
    if (definition.enum) { output.push(rustEnum(name, definition), ''); continue; }
    if (Object.keys(definition).length === 0) { output.push(`pub type ${name} = Value;`, ''); continue; }
    if (definition.oneOf) {
      const variants = definition.oneOf.map((item, index) => {
        const type = rustType(item, `${name}Variant${index + 1}`);
        return `    ${rustUnionVariantName(item, index)}(${type}),`;
      });
      output.push('#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]', '#[serde(untagged)]', `pub enum ${name} {`, ...variants, '}', '');
      continue;
    }
    fail(`cannot generate Rust definition ${name}`);
  }
  return `${output.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

function tsEnum(name, definition) {
  return `export type ${name} = ${definition.enum.map((value) => JSON.stringify(value)).join(' | ')};`;
}

function tsStruct(name, definition) {
  const required = new Set(definition.required ?? []);
  const fields = Object.entries(definition.properties ?? {}).map(([jsonName, property]) => {
    const context = `${name}${jsonName[0].toUpperCase()}${jsonName.slice(1)}`;
    return `  ${tsPropertyName(jsonName)}${required.has(jsonName) ? '' : '?'}: ${tsType(property, context)};`;
  });
  return ['export interface ' + name + ' {', ...fields, '}'].join('\n');
}

function generateTypeScript(schema) {
  const protocol = schema['x-protocol'];
  const output = [
    tsHeader,
    `export const PROTOCOL_NAME = ${JSON.stringify(protocol.name)} as const;`,
    `export const PROTOCOL_MAJOR = ${protocol.major} as const;`,
    `export const PROTOCOL_MINOR = ${protocol.minor} as const;`,
    `export const JSONRPC_VERSION = ${JSON.stringify(protocol.jsonrpcVersion)} as const;`,
    `export const APP_SERVER_METHODS = ${JSON.stringify(schema['x-methods'])} as const;`,
    '',
    typeScriptMethodMapping(schema),
    '',
  ];
  for (const [name, definition] of Object.entries(schema.$defs)) {
    if (definition.$ref) { output.push(`export type ${name} = ${refName(definition.$ref)};`, ''); continue; }
    if (definition.type === 'object') { output.push(tsStruct(name, definition), ''); continue; }
    if (definition.enum) { output.push(tsEnum(name, definition), ''); continue; }
    if (Object.keys(definition).length === 0) { output.push(`export type ${name} = unknown;`, ''); continue; }
    if (definition.oneOf) { output.push(`export type ${name} = ${definition.oneOf.map((item) => tsType(item, name)).join(' | ')};`, ''); continue; }
    fail(`cannot generate TypeScript definition ${name}`);
  }
  return `${output.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

async function main() {
  const check = process.argv[2] === '--check' && process.argv.length === 3;
  if (process.argv.length > 2 && !check) fail('only --check is supported');
  const schema = loadSchema(await readFile(schemaPath, 'utf8'));
  const expected = [[rustPath, generateRust(schema)], [tsPath, generateTypeScript(schema)]];
  if (check) {
    const mismatches = [];
    for (const [path, content] of expected) {
      let current;
      try { current = await readFile(path, 'utf8'); } catch (error) { if (error.code === 'ENOENT') { mismatches.push(`${path} (missing)`); continue; } throw error; }
      if (current !== content) mismatches.push(path);
    }
    if (mismatches.length) fail(`generated files are stale:\n${mismatches.map((path) => `- ${path}`).join('\n')}`);
    console.log('App Server protocol generated files are up to date.');
    return;
  }
  for (const [path, content] of expected) await writeFile(path, content, 'utf8');
  console.log(`Generated ${expected.length} App Server protocol files.`);
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
