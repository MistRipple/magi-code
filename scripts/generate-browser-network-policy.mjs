#!/usr/bin/env node

/* 从 network-policy.json 的唯一规则生成 Rust 与 TypeScript 的浏览器网络边界常量。 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'contracts/desktop-browser/network-policy.json');
const rustPath = resolve(root, 'crates/magi-browser-authority/src/browser_network_policy.generated.rs');
const tsPath = resolve(root, 'contracts/desktop-browser/src/browser-network-policy.generated.ts');
const checkOnly = process.argv.includes('--check');

const LISTS = [
  ['blockedHostnames', 'BLOCKED_HOSTNAMES', 'hostname'],
  ['blockedCidrs', 'BLOCKED_CIDRS', 'cidr'],
  ['loopbackHostnames', 'LOOPBACK_HOSTNAMES', 'hostname'],
  ['loopbackCidrs', 'LOOPBACK_CIDRS', 'cidr'],
  ['privateNetworkCidrs', 'PRIVATE_NETWORK_CIDRS', 'cidr'],
];

function fail(message) {
  throw new Error(`Browser network policy generation failed: ${message}`);
}

function validateCidr(value) {
  const [address, prefix, ...rest] = value.split('/');
  if (rest.length > 0 || address === undefined || prefix === undefined || !/^\d{1,3}$/u.test(prefix)) {
    fail(`CIDR 无效: ${value}`);
  }
  const isV6 = address.includes(':');
  const max = isV6 ? 128 : 32;
  if (Number(prefix) > max) fail(`CIDR 前缀超出范围: ${value}`);
  if (!isV6 && !/^\d{1,3}(\.\d{1,3}){3}$/u.test(address)) fail(`IPv4 地址无效: ${value}`);
  if (isV6 && !/^[0-9a-f:]+$/iu.test(address)) fail(`IPv6 地址无效: ${value}`);
}

function load(source) {
  const result = {};
  for (const [key, , kind] of LISTS) {
    const values = source[key];
    if (!Array.isArray(values) || values.length === 0 || values.some((item) => typeof item !== 'string' || !item)) {
      fail(`${key} 必须是非空字符串数组`);
    }
    for (const value of values) {
      if (kind === 'cidr') validateCidr(value);
      else if (value !== value.toLowerCase() || value.endsWith('.')) fail(`主机名必须是小写且不带结尾点: ${value}`);
    }
    result[key] = values;
  }
  const vectors = source.vectors;
  for (const name of ['alwaysBlocked', 'allowed', 'blockedWhenPrivateNetworkDisallowed', 'allowedEvenWhenPrivateNetworkDisallowed']) {
    if (!Array.isArray(vectors?.[name]) || vectors[name].length === 0) fail(`vectors.${name} 必须是非空数组`);
  }
  return result;
}

function renderRust(policy) {
  const lines = [
    '// @generated by scripts/generate-browser-network-policy.mjs from contracts/desktop-browser/network-policy.json.',
    '// DO NOT EDIT. Change the source and rerun: npm run browser-network-policy:generate',
    '',
  ];
  for (const [key, name] of LISTS) {
    lines.push('#[rustfmt::skip]', `pub const ${name}: &[&str] = &[`);
    for (const value of policy[key]) lines.push(`    ${JSON.stringify(value)},`);
    lines.push('];', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function renderTypeScript(policy) {
  const lines = [
    '// @generated by scripts/generate-browser-network-policy.mjs from contracts/desktop-browser/network-policy.json.',
    '// DO NOT EDIT. Change the source and rerun: npm run browser-network-policy:generate',
    '',
  ];
  for (const [key, name] of LISTS) {
    lines.push(`export const BROWSER_${name}: readonly string[] = [`);
    for (const value of policy[key]) lines.push(`  ${JSON.stringify(value)},`);
    lines.push('];', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

async function writeOrCheck(path, content) {
  if (checkOnly) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== content) fail(`${path.replace(`${root}/`, '')} 已过期，请执行 npm run browser-network-policy:generate`);
    return;
  }
  await writeFile(path, content, 'utf8');
}

const policy = load(JSON.parse(await readFile(sourcePath, 'utf8')));
await Promise.all([
  writeOrCheck(rustPath, renderRust(policy)),
  writeOrCheck(tsPath, renderTypeScript(policy)),
]);
process.stdout.write(`Browser 网络边界规则${checkOnly ? '校验' : '生成'}通过。\n`);
